def first_derivative(spec, window=15, poly=2):
    """
    Savitzky–Golay first derivative
    """
    return savgol_filter(spec, window_length=window,
                         polyorder=poly, deriv=1)

def normalize_derivative(d):
    """
    Normalize derivative spectrum
    """
    return d / (np.mean(np.abs(d)) + 1e-8)

