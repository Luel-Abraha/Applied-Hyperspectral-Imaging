def spectral_angle(cube, ref):
    num = np.sum(cube * ref, axis=-1)
    den = np.linalg.norm(cube, axis=-1) * np.linalg.norm(ref)
    return np.arccos(np.clip(num / (den + 1e-8), -1, 1))

